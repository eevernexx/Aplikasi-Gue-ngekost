function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Pure translate (usable outside React via getLang()). */
export function translate(key, vars, lang = getLang()) {
  const table = dict[lang] || dict.id;
  const value = table[key] ?? dict.id[key] ?? key;
  return interpolate(value, vars);
}

/** Localized display label for a stored value; Indonesian stays as-is. */
export function label(kind, value, lang = getLang()) {
  if (lang !== 'en') return value;
  const map = labelMaps[kind];
  return (map && map[value]) || value;
}

/** React hook: re-renders on language change. */
export function useT() {
  const lang = useLangStore((s) => s.lang);
  const setLang = useLangStore((s) => s.setLang);
  const toggleLang = useLangStore((s) => s.toggleLang);
  const t = (key, vars) => translate(key, vars, lang);
  const lng = (kind, value) => label(kind, value, lang);
  return { t, lng, lang, setLang, toggleLang };
}
